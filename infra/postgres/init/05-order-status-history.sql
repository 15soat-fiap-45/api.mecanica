BEGIN;

CREATE TABLE IF NOT EXISTS service_order.order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id VARCHAR(36) NOT NULL REFERENCES service_order.orders(id) ON DELETE CASCADE,
    status VARCHAR(20) NOT NULL CONSTRAINT order_status_history_status_check CHECK (
        status IN ('PENDING', 'AWAITING_APPROVAL', 'REJECTED', 'APPROVED', 'IN_PROGRESS', 'PAUSED', 'COMPLETED', 'DELIVERED', 'CANCELLED')
    ),
    value_cents BIGINT CONSTRAINT order_status_history_value_cents_check CHECK (
        value_cents IS NULL OR value_cents >= 0
    ),
    changed_by VARCHAR(320),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE service_order.order_status_history
    ADD COLUMN IF NOT EXISTS changed_by VARCHAR(320);

CREATE INDEX IF NOT EXISTS order_status_history_order_id_idx
    ON service_order.order_status_history(order_id, id);

COMMIT;
