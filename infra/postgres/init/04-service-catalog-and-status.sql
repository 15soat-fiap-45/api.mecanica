BEGIN;
ALTER TABLE service_order.orders DROP CONSTRAINT IF EXISTS orders_status_check;
ALTER TABLE service_order.orders ADD CONSTRAINT orders_status_check
    CHECK (status IN ('PENDING', 'AWAITING_APPROVAL', 'REJECTED', 'APPROVED', 'IN_PROGRESS', 'PAUSED', 'COMPLETED', 'DELIVERED', 'CANCELLED'));

CREATE TABLE IF NOT EXISTS service_order.services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(20) NOT NULL,
    description VARCHAR(200),
    value_cents BIGINT NOT NULL CONSTRAINT services_value_cents_check CHECK (value_cents >= 0)
);

CREATE TABLE IF NOT EXISTS service_order.service_parts (
    service_id BIGINT NOT NULL REFERENCES service_order.services(id),
    part_id BIGINT NOT NULL,
    PRIMARY KEY (service_id, part_id)
);

CREATE TABLE IF NOT EXISTS service_order.order_services (
    order_id VARCHAR(36) NOT NULL REFERENCES service_order.orders(id) ON DELETE CASCADE,
    service_id BIGINT NOT NULL REFERENCES service_order.services(id),
    title VARCHAR(20) NOT NULL,
    value_cents BIGINT NOT NULL CONSTRAINT order_services_value_cents_check CHECK (value_cents >= 0),
    PRIMARY KEY (order_id, service_id)
);
COMMIT;
