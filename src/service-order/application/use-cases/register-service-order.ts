import type { ServiceOrderRepository } from '../../domain/service-order/service-order.repository.js';
import { ServiceOrder } from '../../domain/service-order/service-order.js';
import type { EventBus } from '../../../shared/application/event-bus.js';
import type { UseCase } from '../../../shared/application/use-case.js';
import { ApplicationException } from '../../../shared/application/application-exception.js';
import type { VehicleContactLookup } from '../ports/vehicle-contact.js';

export class VehicleNotFoundError extends ApplicationException {
    constructor() {
        super('Vehicle not found.');
    }
}

export interface RegisterServiceOrderInput {
    description: string;
    vehicleId: string;
    valueCents?: number | null | undefined;
}

export interface RegisterServiceOrderOutput {
    id: string;
    description: string;
    status: string;
    vehicleId: string;
    valueCents: number | null;
}

export class RegisterServiceOrder implements UseCase<
    RegisterServiceOrderInput,
    RegisterServiceOrderOutput
> {
    constructor(
        private readonly serviceOrderRepository: ServiceOrderRepository,
        private readonly contacts: VehicleContactLookup,
        private readonly eventBus?: EventBus,
    ) {}

    async execute(
        input: RegisterServiceOrderInput,
    ): Promise<RegisterServiceOrderOutput> {
        // The id is always generated by ServiceOrderId: a caller-chosen id
        // would let a retried request overwrite an existing order (items
        // and status).
        if (!(await this.contacts.findByVehicleId(input.vehicleId)))
            throw new VehicleNotFoundError();
        const serviceOrder = ServiceOrder.register({
            description: input.description,
            vehicleId: input.vehicleId,
            valueCents: input.valueCents,
        });

        await this.serviceOrderRepository.save(serviceOrder);

        if (this.eventBus) {
            await this.eventBus.publish(serviceOrder.pullEvents());
        }

        return {
            id: serviceOrder.id.value,
            description: serviceOrder.description,
            status: serviceOrder.status.value,
            vehicleId: input.vehicleId,
            valueCents: serviceOrder.valueCents,
        };
    }
}
